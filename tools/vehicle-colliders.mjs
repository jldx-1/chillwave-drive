/** Derive bumper/fender collision footprints from the shipped canonical GLBs. */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { Matrix4, Vector3, Quaternion } from 'three';
const models={player:['player/sports-car',.80],sedan:['traffic/sedan',.85],suv:['traffic/suv',1.10],pickup:['traffic/pickup-truck',1.10],truck:['traffic/box-truck',1.45],hatchback:['traffic/hatchback',.80],sport:['traffic/sports-coupe',.80],police:['police/police-suv',1.10]};
const cross=(a,b,c)=>(b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0]);
function hull(points) {
 const sorted=[...new Map(points.map(p=>[p.join(','),p])).values()].sort((a,b)=>a[0]-b[0]||a[1]-b[1]),lo=[],hi=[];
 for(const p of sorted){while(lo.length>1&&cross(lo.at(-2),lo.at(-1),p)<=0)lo.pop();lo.push(p);}
 for(const p of sorted.toReversed()){while(hi.length>1&&cross(hi.at(-2),hi.at(-1),p)<=0)hi.pop();hi.push(p);}
 return [...lo.slice(0,-1),...hi.slice(0,-1)];
}
const profiles={};
for(const [kind,[path,height]] of Object.entries(models)){
 const bytes=await readFile(new URL('../public/assets/vehicles/'+path+'.glb',import.meta.url));
 const size=bytes.readUInt32LE(12),json=JSON.parse(bytes.subarray(20,20+size).toString()),bin=bytes.subarray(28+size),points=[];
 function visit(index,parent,excluded=false){
  const node=json.nodes[index],local=node.matrix?new Matrix4().fromArray(node.matrix):new Matrix4().compose(new Vector3().fromArray(node.translation??[0,0,0]),new Quaternion().fromArray(node.rotation??[0,0,0,1]),new Vector3().fromArray(node.scale??[1,1,1])),world=parent.clone().multiply(local);
  excluded||=/^(?:Wheel_|Spin|Mirror_|Wiper_|Steering)/i.test(node.name??'');
  if(!excluded&&node.mesh!==undefined)for(const primitive of json.meshes[node.mesh].primitives){
   const role=json.materials[primitive.material]?.extras?.vehicleRole;
   if(!['paint','trim','metal','head','brake'].includes(role))continue;
   const a=json.accessors[primitive.attributes.POSITION],view=json.bufferViews[a.bufferView];
   if(a.componentType!==5126)throw new Error('Canonical positions must be float32');
   const stride=view.byteStride??12,start=(view.byteOffset??0)+(a.byteOffset??0);
   for(let i=0;i<a.count;i++){
    const p=new Vector3(bin.readFloatLE(start+i*stride),bin.readFloatLE(start+i*stride+4),bin.readFloatLE(start+i*stride+8)).applyMatrix4(world);
    if(p.y>=.18&&p.y<=height)points.push([Math.round(p.x*10000)/10000,Math.round(-p.z*10000)/10000]);
   }
  }
  for(const child of node.children??[])visit(child,world,excluded);
 }
 for(const index of json.scenes[json.scene??0].nodes)visit(index,new Matrix4());
 const outline=hull(points),original=outline.slice();
 // Remove nearly collinear surface detail, keeping bumper/fender deviations below 15 mm.
 let changed=true;while(changed&&outline.length>8){changed=false;for(let i=0;i<outline.length;i++){const a=outline[(i+outline.length-1)%outline.length],b=outline[i],c=outline[(i+1)%outline.length];if(Math.abs(cross(a,c,b))/Math.hypot(c[0]-a[0],c[1]-a[1])<.015&&original.every(p=>cross(a,c,p)/Math.hypot(c[0]-a[0],c[1]-a[1])>=-.015)){outline.splice(i,1);changed=true;break;}}}
 const xs=outline.map(p=>p[0]),ss=outline.map(p=>p[1]);
 profiles[kind]={width:Math.max(...xs)-Math.min(...xs),length:Math.max(...ss)-Math.min(...ss),hull:outline,sourceSha256:createHash('sha256').update(bytes).digest('hex'),height};
 console.log(kind,profiles[kind].width.toFixed(3),profiles[kind].length.toFixed(3),outline.length);
}
await writeFile(new URL('../src/drive/collision-profiles.ts',import.meta.url),'/** Generated by tools/vehicle-colliders.mjs from canonical GLBs. Local [right, forward] metres; excludes mirrors, wings and wheel assemblies. */\nexport type CollisionHull = ReadonlyArray<readonly [number, number]>;\nexport interface CollisionProfile { width:number; length:number; hull:CollisionHull; sourceSha256:string; height:number }\nexport const COLLISION_PROFILES: Record<'+Object.keys(models).map(k=>"'"+k+"'").join(' | ')+', CollisionProfile> = '+JSON.stringify(profiles,null,2)+';\n');
